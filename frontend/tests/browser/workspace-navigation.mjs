import test from 'node:test';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';

test('chat navigation shows real conversation state and opens as a keyboard-safe mobile drawer', async () => {
  const url = process.env.BINTANONG_BROWSER_URL;
  assert.ok(url && ['localhost', '127.0.0.1'].includes(new URL(url).hostname));
  const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ storageState: process.env.BINTANONG_BROWSER_STATE, viewport: { width: 1440, height: 900 } });
    const page = await context.newPage(), submissions = [];
    page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/chat') submissions.push(request); });
    await page.goto(new URL('/chat', url).href, { waitUntil: 'networkidle' });
    const history = page.getByRole('navigation', { name: 'Chat history', exact: true });
    await history.waitFor({ timeout: 3000 });
    assert.equal(await page.getByRole('navigation', { name: 'Example questions' }).count(), 0);
    assert.equal(await history.getByRole('button').count(), 0, 'no invented conversations before the first message');
    await history.getByText('No chats yet.', { exact: true }).waitFor();
    const heading = await page.getByRole('heading', { level: 1 }).boundingBox();
    const composer = await page.locator('.composer').boundingBox();
    assert.ok(composer.y - heading.y - heading.height < 180, 'starter and composer form one focused area');
    const input = page.getByRole('textbox', { name: 'Your question' });
    await input.fill('A draft to keep');
    await page.getByRole('button', { name: 'Program and curriculum', exact: true }).click();
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Files in this chat', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await input.inputValue(), 'A draft to keep');
    assert.equal(submissions.length, 0, 'context controls must never submit the composer form');
    await page.getByRole('button', { name: 'Close navigation', exact: true }).click({ timeout: 2500 });
    assert.equal(await history.count(), 0);
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await history.waitFor();
    await input.fill('Synthetic sidebar history question');
    await page.getByRole('button', { name: 'Send question', exact: true }).click();
    await page.locator('.source-link').first().waitFor();
    const currentChat = history.getByRole('button', { name: 'Synthetic sidebar history question', exact: true });
    assert.equal(await currentChat.getAttribute('aria-current'), 'page');
    assert.equal(await history.getByRole('button').count(), 1);
    await input.fill('Keep this next question');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByRole('dialog', { name: 'Navigation', exact: true }).waitFor();
    assert.equal(await page.getByRole('dialog').evaluate(node => node.getAnimations().length), 0);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Open navigation');
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Synthetic sidebar history question', exact: true }).click();
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.getByRole('textbox', { name: 'Your question' }).inputValue(), 'Keep this next question');
    assert.equal(await page.getByRole('article', { name: 'Your message', exact: true }).count(), 1);
    assert.equal(submissions.length, 1, 'opening the current chat never sends or replays a question');
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'New chat', exact: true }).click();
    await page.getByRole('button', { name: 'Clear chat', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    assert.equal(await page.getByRole('dialog').getByRole('navigation', { name: 'Chat history' }).getByRole('button').count(), 0);
    assert.equal(submissions.length, 1);
  } finally { await browser.close(); }
});
