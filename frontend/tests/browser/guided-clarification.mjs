import test from 'node:test';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';

test('live clarification requires confirmation, preserves drafts and can resume after dismissal', async () => {
  const url = process.env.BINTANONG_BROWSER_URL;
  assert.ok(url && ['localhost', '127.0.0.1'].includes(new URL(url).hostname));
  const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ storageState: process.env.BINTANONG_BROWSER_STATE, viewport: { width: 390, height: 844 } });
    const page = await context.newPage(), submissions = [], errors = [];
    page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/chat') submissions.push(request.postDataJSON()); });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(new URL('/chat', url).href, { waitUntil: 'networkidle' });
    const input = page.getByRole('textbox', { name: 'Your question' });
    await input.fill('Synthetic guided clarification');
    await page.getByRole('button', { name: 'Send question', exact: true }).click();
    await page.getByRole('button', { name: 'Continue clarification', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'A little more detail', exact: true });
    await dialog.waitFor({ timeout: 15000 });
    assert.equal(await dialog.locator('input:checked').count(), 0);
    assert.equal(await dialog.getByRole('button', { name: 'Continue', exact: true }).isDisabled(), true);
    await dialog.getByRole('radio', { name: "I don't know", exact: true }).check();
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByRole('radio', { name: 'Currently enrolled', exact: true }).check();
    await dialog.getByRole('textbox', { name: 'Explain another way or add a detail' }).fill('Actually, I dropped it yesterday.');
    await page.keyboard.press('Escape');
    await page.route('**/api/session', route => route.fulfill({ status: 503, json: { error: 'synthetic_clear_failed' } }));
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByRole('button', { name: 'New chat', exact: true }).click();
    await page.getByRole('button', { name: 'Clear chat', exact: true }).click();
    await page.getByText('Clearing was not confirmed. Your conversation and files are still here.', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    await input.fill('Keep this next question');
    const resume = page.getByRole('button', { name: 'Continue clarification', exact: true });
    await resume.click();
    assert.equal(await dialog.getByRole('radio', { name: 'Currently enrolled', exact: true }).isChecked(), true);
    assert.equal(await dialog.getByRole('textbox').inputValue(), 'Actually, I dropped it yesterday.');
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByRole('heading', { name: 'Review your reply', exact: true }).waitFor();
    assert.equal(submissions.length, 1, 'selection, navigation and review never send');
    assert.ok((await dialog.innerText()).includes('I do not know whether I have passed B2/L.'));
    const overflow = await dialog.evaluate(node => node.scrollWidth > node.clientWidth + 1);
    assert.equal(overflow, false);
    if (process.env.BINTANONG_BROWSER_EVIDENCE) await page.screenshot({ path: process.env.BINTANONG_BROWSER_EVIDENCE + '/clarification-review-mobile.png' });
    await dialog.getByRole('button', { name: 'Confirm and send', exact: true }).dblclick();
    await dialog.waitFor({ state: 'detached' });
    await page.locator('.source-link').first().waitFor();
    assert.equal(submissions.length, 2, 'one explicit confirmation sends once');
    const sent = submissions[1].messages[0].parts[0].text;
    assert.match(sent, /Synthetic guided clarification/);
    assert.match(sent, /I do not know whether I have passed B2\/L/);
    assert.match(sent, /Actually, I dropped it yesterday/);
    assert.equal(await input.inputValue(), 'Keep this next question');
    assert.equal(await resume.count(), 0, 'old prompt cannot submit after another turn');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});

test('scope clarification uses listed curricula and keeps unknown or alternative answers explicit', async () => {
  const url = process.env.BINTANONG_BROWSER_URL;
  assert.ok(url && ['localhost', '127.0.0.1'].includes(new URL(url).hostname));
  const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ storageState: process.env.BINTANONG_BROWSER_STATE, viewport: { width: 320, height: 800 } });
    const page = await context.newPage(), submissions = [];
    page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/chat') submissions.push(request.postDataJSON()); });
    await page.goto(new URL('/chat', url).href, { waitUntil: 'networkidle' });
    const curricula = await (await context.request.get(new URL('/api/curricula', url).href)).json();
    await page.getByRole('button', { name: 'Chat options', exact: true }).click();
    await page.getByLabel('Appearance', { exact: true }).selectOption('dark');
    await page.keyboard.press('Escape');
    await page.getByRole('textbox', { name: 'Your question' }).fill('Synthetic clarification');
    await page.getByRole('button', { name: 'Send question', exact: true }).click();
    await page.getByRole('button', { name: 'Continue clarification', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.waitFor();
    const choice = dialog.getByRole('combobox');
    assert.equal(await choice.inputValue(), '', 'no curriculum is preselected');
    assert.equal(await choice.locator('option').count(), curricula.curricula.length + 3);
    await choice.selectOption(curricula.curricula[0].curriculumId);
    await dialog.getByRole('textbox').fill('I am a transferee.');
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByRole('button', { name: 'Back', exact: true }).click();
    await choice.selectOption('unknown');
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    assert.ok((await dialog.innerText()).includes('I do not know this detail.'));
    await dialog.getByRole('button', { name: 'Back', exact: true }).click();
    await choice.selectOption('other');
    await dialog.getByRole('textbox').fill('');
    assert.equal(await dialog.getByRole('button', { name: 'Continue', exact: true }).isDisabled(), true);
    await dialog.getByRole('textbox').fill('I do not know the edition; I transferred this year.');
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
    assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth + 1), false);
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    assert.equal(submissions.length, 1);
    if (process.env.BINTANONG_BROWSER_EVIDENCE) await page.screenshot({ path: process.env.BINTANONG_BROWSER_EVIDENCE + '/clarification-scope-dark-200.png' });
    assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth + 1), false, 'review and confirmation must also reflow');
    await page.keyboard.press('Escape');
    const resume = page.getByRole('button', { name: 'Continue clarification', exact: true });
    await resume.click();
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Continue clarification');
    await resume.click();
    await dialog.getByRole('button', { name: 'Back', exact: true }).click();
    await choice.selectOption(curricula.curricula[0].curriculumId);
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByRole('button', { name: 'Confirm and send', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    assert.equal(submissions.length, 2);
    assert.equal(submissions[1].programId, curricula.curricula[0].programId);
    assert.equal(submissions[1].curriculumId, curricula.curricula[0].curriculumId);
    assert.match(submissions[1].messages[0].parts[0].text, /I do not know the edition; I transferred this year/);
  } finally { await browser.close(); }
});
