"""Real role/privilege regressions in a disposable database; no shared cleanup."""

import unittest

from tests.storage_database import FIXTURE, StorageDatabase


class TestStorageSecurity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.db = StorageDatabase()

    @classmethod
    def tearDownClass(cls):
        cls.db.close()

    def test_runtime_has_no_mutation_privileges(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                grants = self.db.json(f"""
                    select coalesce(json_agg(c.relname || ':' || p.privilege), '[]')
                    from pg_class c join pg_namespace n on n.oid=c.relnamespace
                    cross join (values ('INSERT'),('UPDATE'),('DELETE'),('TRUNCATE'),
                                      ('REFERENCES'),('TRIGGER'),('MAINTAIN')) p(privilege)
                    where n.nspname='public' and c.relkind='r'
                      and has_table_privilege('{role}',c.oid,p.privilege);
                """)
                self.assertEqual(grants, [], "runtime role retains destructive grants")

    def test_operational_tables_have_explicit_restrictive_denials(self):
        policies = self.db.json("""
            select coalesce(json_agg(c.relname order by c.relname),'[]')
            from pg_policy p join pg_class c on c.oid=p.polrelid
            where c.relname in ('ingestion_runs','evaluation_runs')
                and p.polname='p4_operational_runtime_deny' and not p.polpermissive
                and pg_get_expr(p.polqual,p.polrelid)='false'
                and pg_get_expr(p.polwithcheck,p.polrelid)='false';
        """)
        self.assertEqual(policies, ['evaluation_runs', 'ingestion_runs'])

    def test_administrative_and_private_functions_have_no_runtime_execute(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                exposed = self.db.json(f"""
                    select coalesce(json_agg(n.nspname||'.'||p.proname),'[]')
                    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
                    where n.nspname in ('public','bintanong_private') and p.proname<>'match_chunks'
                        and has_function_privilege('{role}',p.oid,'EXECUTE');
                """)
                self.assertEqual(exposed, [])

    def test_database_hash_matches_contract_canonicalization(self):
        from backend.bintanong_contracts.source import compute_content_hash
        from tests.storage_database import sql_literal
        for text in ('Simple text', 'Unicode: café 🔎', 'e\u0301\tspaces\u00a0\u2000here', '\u001c leading \u0085 and\u3000trailing ', 'Quotes " and slash \\'):
            with self.subTest(text=text):
                actual = self.db.json(f"select to_json(bintanong_private.content_hash(null,{sql_literal(text)}));")
                self.assertEqual(actual, compute_content_hash(None,text))

    def test_publication_rejects_stale_transaction_snapshots(self):
        db = StorageDatabase()
        self.addCleanup(db.close)
        db.execute(FIXTURE + "commit;")
        for level in ("repeatable read", "serializable"):
            result = db._command(db.name, f"begin isolation level {level}; select public.activate_knowledge_release('release-test1'); commit;")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("READ COMMITTED isolation", result.stderr)

    def test_new_tables_and_sequences_are_not_exposed_by_default(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                grants = self.db.json(f"""
                    begin;
                    create table public.future_test_table(id bigint generated by default as identity);
                    create function public.future_test_function() returns integer language sql as 'select 1';
                    select json_build_array(
                        has_table_privilege('{role}','public.future_test_table','SELECT'),
                        has_table_privilege('{role}','public.future_test_table','TRUNCATE'),
                        has_sequence_privilege('{role}','public.future_test_table_id_seq','USAGE'),
                        has_function_privilege('{role}','public.future_test_function()','EXECUTE'));
                    rollback;
                """)
                self.assertEqual(grants, [False, False, False, False])

    def test_draft_children_and_unreleased_rules_are_hidden(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                counts = self.db.json(FIXTURE + f"""
                    set local role {role};
                    select json_build_array(
                        (select count(*) from public.courses),
                        (select count(*) from public.course_aliases),
                        (select count(*) from public.policy_rules),
                        (select count(*) from public.rule_source_spans),
                        (select count(*) from public.release_chunks),
                        (select count(*) from public.release_document_versions));
                    rollback;
                """)
                self.assertEqual(counts, [0] * 6)

    def test_active_release_exposes_only_approved_related_evidence(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                rows = self.db.json(FIXTURE + f"""
                    select public.activate_knowledge_release('release-test1');
                    set local role {role};
                    select json_build_array(
                        (select json_agg(course_id order by course_id) from public.courses),
                        (select json_agg(raw_code order by raw_code) from public.course_aliases),
                        (select json_agg(rule_id order by rule_id) from public.policy_rules),
                        (select count(*) from public.rule_source_spans),
                        (select count(*) from public.source_spans),
                        (select count(*) from public.chunk_embeddings));
                    rollback;
                """)
                self.assertEqual(rows, [["course-test"], ["TEST-ALIAS"], ["rule-test"], 1, 1, 1])

    def test_activation_rejects_incomplete_or_unapproved_evidence(self):
        invalid = {
            "unapproved_document": "update public.document_versions set approval_state='requested' where version_id='ver-test1';",
            "unverified_document": "update public.document_versions set verification_state='pending' where version_id='ver-test1';",
            "unreviewed_chunk": "update public.chunks set content_review='pending' where chunk_id=repeat('a',64);",
            "missing_embedding": "delete from public.chunk_embeddings where chunk_id=repeat('a',64);",
            "wrong_embedding_hash": "update public.chunk_embeddings set chunk_content_hash=repeat('f',64) where chunk_id=repeat('a',64);",
            "unnormalized_vector": "update public.chunk_embeddings set embedding=('[' || '2,' || repeat('0,',1022) || '0]')::extensions.vector where chunk_id=repeat('a',64);",
            "wrong_configuration": "update public.embedding_sets set normalization='none' where embedding_set_id='set-test';",
            "missing_source_span": "delete from public.source_spans where chunk_id=repeat('a',64);",
            "wrong_source_span": "update public.source_spans set version_id='ver-test2' where chunk_id=repeat('a',64);",
            "unlocated_source_span": "update public.source_spans set page=null where chunk_id=repeat('a',64);",
            "incomplete_locator": "update public.source_spans set locator='{\"kind\":\"table_cells\"}' where chunk_id=repeat('a',64);",
            "stale_content_hash": "update public.chunks set text='Changed text' where chunk_id=repeat('a',64);",
            "source_span_text_mismatch": "update public.source_spans set text='Different printed text' where chunk_id=repeat('a',64);",
            "wrong_document_membership": "delete from public.release_document_versions where release_id='release-test1';",
            "candidate_rule": "update public.policy_rules set approval_state='candidate' where rule_id='rule-test';",
            "missing_rule_provenance": "delete from public.rule_source_spans where rule_id='rule-test';",
            "rule_provenance_outside_release": "update public.rule_source_spans set span_id='22222222-2222-4222-8222-222222222222' where rule_id='rule-test';",
            "expected_count_mismatch": "update public.knowledge_releases set expected_chunk_count=2 where release_id='release-test1';",
            "missing_model_revision": "update public.embedding_sets set model_revision='latest' where embedding_set_id='set-test';",
            "revoked_release": "update public.knowledge_releases set status='revoked' where release_id='release-test1';",
        }
        for name, mutation in invalid.items():
            with self.subTest(case=name):
                rejected = self.db.json(FIXTURE + mutation + """
                    create function pg_temp.activation_denied() returns boolean
                    language plpgsql as $$ begin
                        perform public.activate_knowledge_release('release-test1');
                        return false;
                    exception when check_violation then return true;
                    end; $$;
                    select to_json(pg_temp.activation_denied());
                    rollback;
                """)
                self.assertTrue(rejected, f"activation accepted {name}")

    def test_published_content_and_memberships_are_immutable(self):
        changes = {
            "chunk": "update public.chunks set text='CORRUPTED' where chunk_id=repeat('a',64)",
            "document_version": "update public.document_versions set filename='changed.pdf' where version_id='ver-test1'",
            "source_span": "delete from public.source_spans where chunk_id=repeat('a',64)",
            "embedding_set": "update public.embedding_sets set model_revision=repeat('f',64) where embedding_set_id='set-test'",
            "embedding": "delete from public.chunk_embeddings where chunk_id=repeat('a',64)",
            "course": "update public.courses set course_title='CORRUPTED' where course_id='course-test'",
            "curriculum": "update public.curriculum_versions set approval_status='draft' where curriculum_version_id='curriculum-test'",
            "rule": "update public.policy_rules set specification='CORRUPTED' where rule_id='rule-test'",
            "rule_provenance": "delete from public.rule_source_spans where rule_id='rule-test'",
            "membership_delete": "delete from public.release_chunks where release_id='release-test1'",
            "membership_insert": "insert into public.release_chunks(release_id,chunk_id) values ('release-test1',repeat('b',64))",
            "release_configuration": "update public.knowledge_releases set description='CORRUPTED' where release_id='release-test1'",
            "unreleased_embedding_in_published_set": "update public.chunk_embeddings set token_count='{\"changed\":1}' where chunk_id=repeat('b',64)",
            "truncate_membership": "truncate public.release_rules",
        }
        for name, change in changes.items():
            with self.subTest(case=name):
                rejected = self.db.json(FIXTURE + """
                    select public.activate_knowledge_release('release-test1');
                    create function pg_temp.mutation_denied() returns boolean
                    language plpgsql as $$ begin
                """ + change + "; return false; exception when object_not_in_prerequisite_state then return true; end; $$;" + """
                    select to_json(pg_temp.mutation_denied());
                    rollback;
                """)
                self.assertTrue(rejected, f"published {name} remained mutable")

    def test_transition_and_rollback_isolate_chunks_and_vectors(self):
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                observed = self.db.json(FIXTURE + f"""
                    select public.activate_knowledge_release('release-test1');
                    select public.activate_knowledge_release('release-test2');
                    select public.rollback_knowledge_release('release-test1');
                    set local role {role};
                    select json_build_array(
                        (select json_agg(chunk_id) from public.chunks),
                        (select count(*) from public.match_chunks(('[' || '1,' || repeat('0,',1022) || '0]')::extensions.vector,0.5,10)));
                    rollback;
                """)
                self.assertEqual(observed, [["a" * 64], 1])


if __name__ == "__main__":
    unittest.main()
